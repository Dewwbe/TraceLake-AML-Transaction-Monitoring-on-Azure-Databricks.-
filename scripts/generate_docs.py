"""Generate sql/ddl/*.sql and docs/data_model.md from the table registry (src/aml/schemas.py).

Usage: python scripts/generate_docs.py [--check]
With --check the script exits non-zero if the committed files are out of date (used by CI/tests).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from aml.schemas import TABLES

ROOT = Path(__file__).resolve().parents[1]
LAYERS = [("bronze", "Bronze (raw)"), ("silver", "Silver (validated)"), ("gold", "Gold (serving)"), ("ops", "Operations")]

ERD = """```mermaid
erDiagram
    DIM_DATE ||--o{ FACT_TRANSACTION : date_key
    DIM_ACCOUNT ||--o{ FACT_TRANSACTION : sender_receiver
    DIM_CUSTOMER ||--o{ DIM_ACCOUNT : owns
    DIM_CUSTOMER ||--o{ FACT_ALERT : "point-in-time customer_key"
    DIM_RULE ||--o{ FACT_ALERT : rule_id
    DIM_DATE ||--o{ FACT_ALERT : alert_date_key
    FACT_CASE ||--o{ FACT_ALERT : case_id
    DIM_CUSTOMER ||--o{ FACT_SCREENING : customer_id
    DIM_COUNTRY ||--o{ FACT_TRANSACTION : "sender/receiver country (SCD2 lookup)"
```
"""


def render_ddl() -> dict[str, str]:
    files: dict[str, str] = {}
    schemas = sorted({t.schema_name for t in TABLES.values()})
    head = "-- Generated by scripts/generate_docs.py from src/aml/schemas.py. Do not edit by hand.\n"
    files["00_schemas.sql"] = head + "".join(f"CREATE SCHEMA IF NOT EXISTS ${{catalog}}.{s};\n" for s in schemas)
    for i, (layer, _) in enumerate(LAYERS, start=1):
        body = "\n".join(t.create_sql() for t in TABLES.values() if t.layer == layer)
        files[f"{i}0_{layer}.sql"] = head + "\n" + body
    return files


def render_model() -> str:
    out = [
        "# Data model",
        "",
        "Generated by `scripts/generate_docs.py` from `src/aml/schemas.py`. Do not edit by hand.",
        "",
        f"{len(TABLES)} tables across four schemas. Unity Catalog names are `<catalog>.<schema>.<table>`; "
        "local runs use parquet under `data/lake/<schema>/<table>`.",
        "",
        "## Gold star schema",
        "",
        ERD,
        "SCD Type 2 dimensions: `gold.dim_customer` (profile and risk rating) and `gold.dim_country` "
        "(risk tier). `fact_alert.customer_key` is a point-in-time join (`valid_from <= alert_ts < valid_to`).",
        "",
        "## Tables",
        "",
        "| Table | Layer | Grain / primary key | Load pattern |",
        "|---|---|---|---|",
    ]
    for t in TABLES.values():
        out.append(f"| `{t.name}` | {t.layer} | {', '.join(f'`{k}`' for k in t.pk)} | {t.load} |")
    for layer, title in LAYERS:
        out += ["", f"## {title}", ""]
        for t in (x for x in TABLES.values() if x.layer == layer):
            out += [f"### `{t.name}`", "", t.description, "",
                    f"*Key:* {', '.join(f'`{k}`' for k in t.pk)}  ", f"*Load:* {t.load}", "",
                    "| Column | Type | Description |", "|---|---|---|"]
            out += [f"| `{c.name}` | `{c.dtype}` | {c.desc} |" for c in t.cols]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    targets = {ROOT / "sql" / "ddl" / n: c for n, c in render_ddl().items()}
    targets[ROOT / "docs" / "data_model.md"] = render_model()
    stale = []
    for path, content in targets.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        sys.stderr.write("Out of date (run scripts/generate_docs.py): " + ", ".join(stale) + "\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
